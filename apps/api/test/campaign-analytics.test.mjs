import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {CampaignAnalytics,MemoryCampaignRepository,campaignConfig,campaignLink,pakistanDay} from '../src/services/campaign-analytics.mjs';
test('first-touch server attribution persists for 30 days, respects consent and cannot cross users',async()=>{
  let now=Date.parse('2026-11-24T00:10:00+05:00');
  const repo=new MemoryCampaignRepository(),analytics=new CampaignAnalytics({repository:repo,config:{nodeEnv:'test'},clock:()=>now});
  const c=campaignConfig({name:'Campaign A',utm:'M',package:'1',parameter:'ranchers',ref:'partner123',landingPath:'/landing1'});
  await repo.put(c);assert.match(campaignLink(c,'https://example.invalid'),/campaign_id=/);
  const raw={...c.snapshot,parameter:'tampered'};
  const eventId=randomUUID();
  const event=await analytics.publicEvent({headers:{}},{eventId,name:'landing_view',raw,consent:true});
  assert.ok(event.cookie);const cookie=event.cookie.split(';')[0],req={headers:{cookie}};
  assert.equal((await analytics.checkout(req,{raw:{utm:'T'}})).parameter,'ranchers');
  assert.equal((await analytics.publicEvent(req,{eventId,name:'landing_view',raw,consent:true})).accepted,false);
  await analytics.link(req,'account-a');
  const one=await analytics.checkout(req,{userId:'account-a',raw:{utm:'T'}});
  assert.equal(one.parameter,'ranchers');assert.ok(one.attribution_id);
  assert.equal((await analytics.checkout(req,{userId:'account-b',raw:{utm:'T'}})).platform,'TikTok');
  await analytics.stage('jazzcash_initiated',{attemptId:'link-1',attribution:one,userId:'account-a'});
  await analytics.stage('payment_failed',{attemptId:'attempt-1',attribution:one,failureCode:'101'});
  await analytics.stage('payment_failed',{attemptId:'attempt-1',attribution:one,failureCode:'101'});
  const daily=await analytics.daily('2026-11-24');assert.equal(daily.landingViews,1);assert.equal(daily.identifiedUniqueVisitors,1);assert.equal(daily.observedFailedAttempts,1);assert.equal(daily.mpinShown,null);assert.equal(daily.heTraffic,null);
  assert.equal(pakistanDay('2026-11-24').from,'2026-11-23T19:00:00.000Z');
  await analytics.publicEvent(req,{eventId:randomUUID(),name:'landing_view',raw,consent:false});
  assert.equal((await analytics.checkout(req,{raw:{utm:'T'}})).attribution_id,undefined);
  const fresh=await analytics.publicEvent({headers:{}},{eventId:randomUUID(),name:'landing_view',raw,consent:true});now+=31*86400000;
  assert.equal((await analytics.checkout({headers:{cookie:fresh.cookie.split(';')[0]}},{raw:{utm:'G'}})).platform,'Google');
  await assert.rejects(()=>analytics.publicEvent(req,{eventId:randomUUID(),name:'payment_succeeded',raw,consent:true}),/Unsupported/);
});
